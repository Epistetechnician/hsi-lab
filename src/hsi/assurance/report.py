"""Assurance-level report from committed receipts, validator runs, and reproduction reports."""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

from hsi.contracts.io import load_json
from hsi.paths import REPO

LEVELS = [
    ("A1", "Receipt well-formed and digest-bound to a frozen packet"),
    ("A2", "Independent recomputation: stdlib-only validator, fresh process, from counts"),
    (
        "A3",
        (
            "Clean-environment rerun (fresh clone at source commit, fresh venv, original lock)"
            " matches 100% of aggregates"
        ),
    ),
    ("A4", "Rerun by an independent party/machine plus a human spot-check"),
]
ALL = [
    "E1",
    "E2",
    "E3",
    "E4",
    "E4-llm",
    "E5",
    "E6",
    "E6-llm",
    "E6-llmgen",
    "E6-llm7b",
    "E6-ground",
    "E6-confirm",
    "E6-verified",
    "E6-poolctl",
    "E6-ood",
    "E7",
]  # *-llm: MLX-backbone variants


def _packet_for(digest: str) -> Path | None:
    for p in sorted((REPO / "packets").glob("*.frozen.json")):
        if json.loads(p.read_text())["packet_digest"] == digest:
            return p
    return None


def assess() -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    exp = REPO / "docs" / "experiments"
    for e in ALL:
        rp, rep = exp / f"{e}-receipt.json", exp / f"{e}-repro.json"
        if not rp.exists():
            rows.append({"experiment": e, "level": "none", "note": "not run"})
            continue
        r = load_json(rp)
        pf = _packet_for(str(r["packet_digest"]))
        level, note = "A1" if pf else "none", ""
        if pf:
            v = subprocess.run(
                [sys.executable, "-I", str(REPO / "validator" / "recompute.py"), str(rp), str(pf)],
                capture_output=True,
                text=True,
                check=False,
                cwd=tempfile.gettempdir(),
            )
            if v.returncode == 0:
                level = "A2"
            else:
                note = v.stdout.strip()[:120]
        if level == "A2" and rep.exists():
            rr: dict[str, Any] = load_json(rep)
            if (
                rr["match"]
                and rr["rerun_validator_ok"]
                and rr["original_receipt_digest"] == r["receipt_digest"]
            ):
                level = "A3"
            else:
                note = f"rerun mismatches: {rr['mismatches'][:3]}"
        rows.append(
            {
                "experiment": e,
                "decision": r["decision"],
                "level": level,
                "commit": str(r["source_commit"])[:8],
                "note": note,
            }
        )
    return rows


def render(rows: list[dict[str, object]]) -> str:
    out = ["# Assurance report\n", "Generated by `hsi assurance`. Levels:\n"]
    out += [f"- **{k}** — {v}" for k, v in LEVELS]
    out += [
        "",
        "| Experiment | Decision | Assurance | Source commit | Note |",
        "| --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        out.append(
            f"| {r['experiment']} | {r.get('decision', '—')} | {r['level']} | "
            f"{r.get('commit', '—')} | {r['note']} |"
        )
    core = {f"E{i}" for i in range(1, 8)}
    names = ", ".join(str(r["experiment"]) for r in rows if r["experiment"] not in core)
    base = [r for r in rows if r["experiment"] in core]
    var = [r for r in rows if r["experiment"] not in core]
    done = sum(1 for r in base if r["level"] in ("A2", "A3"))
    a3 = sum(1 for r in base if r["level"] == "A3")
    vdone = sum(1 for r in var if r["level"] in ("A2", "A3"))
    va3 = sum(1 for r in var if r["level"] == "A3")
    out += [
        "",
        (
            f"Base experiments E1-E7 with an independently recomputed receipt: {done} of 7. "
            f"Clean-rerun reproduced (A3): {a3} of 7. "
            f"Variants (MLX-backbone and follow-up packets: {names}): "
            f"{vdone} of {len(var)} recomputed, {va3} of {len(var)} reproduced. "
            "A4 (independent party + human spot-check) has not been performed for any experiment."
        ),
    ]
    return "\n".join(out) + "\n"
